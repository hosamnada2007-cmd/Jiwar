function fillGovernorates(select, selected) {
  select.innerHTML = '<option value="">اختر المحافظة</option>' +
    EGYPT.map((g) => `<option value="${g.name}"${g.name === selected ? ' selected' : ''}>${g.name}</option>`).join('');
}

function fillCities(select, governorate, selected) {
  const g = EGYPT.find((x) => x.name === governorate);
  select.innerHTML = '<option value="">اختر المدينة أو المركز</option>' +
    (g ? g.cities.map((c) => `<option value="${c}"${c === selected ? ' selected' : ''}>${c}</option>`).join('') : '');
  select.disabled = !g;
}

function govCenter(governorate) {
  const g = EGYPT.find((x) => x.name === governorate);
  return g ? [g.lat, g.lng] : DEFAULT_CENTER;
}

function bindLocationSelects(govSelect, citySelect, onChange) {
  fillGovernorates(govSelect);
  fillCities(citySelect, '');
  govSelect.addEventListener('change', () => {
    fillCities(citySelect, govSelect.value);
    if (onChange) onChange(govSelect.value);
  });
}
